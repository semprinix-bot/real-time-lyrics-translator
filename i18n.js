// Best match for a browser language tag among the supported languages
function matchLang(tag) {
  const codes = LANGS.map(([c]) => c);
  tag = (tag || 'en').toLowerCase();
  return codes.find((c) => c.toLowerCase() === tag) || codes.find((c) => c.split('-')[0] === tag.split('-')[0]) || 'en';
}

let uiLang = 'en';
const escapeHtml = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

// Plain-text translation (vars are inserted as text)
function t(key, vars = {}) {
  let s = (STRINGS[uiLang] && STRINGS[uiLang][key]) ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)).replace(/<\/?b>/g, '');
}

// Applies the interface language to every [data-i18n*] element
function applyI18n(lang, htmlVars = {}) {
  uiLang = STRINGS[lang] ? lang : 'en';
  document.documentElement.lang = uiLang;
  document.documentElement.dir = RTL_LANGS.has(uiLang) ? 'rtl' : 'ltr';
  const dict = STRINGS[uiLang];
  const raw = (k) => dict[k] ?? STRINGS.en[k] ?? k;
  const vars = { connect: escapeHtml(raw('connect')), ...htmlVars };
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = raw(el.dataset.i18n); });
  // only trusted strings from STRINGS + trusted vars end up in innerHTML
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = raw(el.dataset.i18nHtml).replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = raw(el.dataset.i18nPh); });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = raw(el.dataset.i18nTitle); });
}
